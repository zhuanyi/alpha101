#!/usr/bin/env python3
"""End-to-end smoke test on the symbols already in alpha101.yahoo_ohlcv (read-only).

    PYTHONPATH=src python3 scripts/smoke_test.py [--out docs/smoke_test.md]

Proves the pipeline (DB -> Panel -> raw basis -> parser/evaluator -> one lag function -> rank IC)
on alphas 1, 6, 12 and 101, and evaluates all non-industry alphas once for coverage/timing.
Writes the markdown report; every number in it is computed here. Writes nothing to the DB.
The panel is ~25 US and ~23 TSX symbols including ETFs: a pipeline check, NOT a research result.
"""
from __future__ import annotations

import argparse
import datetime as dt
import time
from pathlib import Path

import numpy as np
import pandas as pd

from alpha101 import EvalOptions, Evaluator, forward_returns, load_alphas
from alpha101.data.yahoo import panel_from_long, read_long
from alpha101.db import reader
from alpha101.stats import ic_summary, rank_ic

ALPHA_IDS = [1, 6, 12, 101]
HORIZONS = [1, 5, 10, 21]
ERAS = [("2005-2012", "2005-01-01", "2012-12-31"), ("2013-2018", "2013-01-01", "2018-12-31"),
        ("2019-2026", "2019-01-01", "2026-12-31")]
MARKETS = {"US": "^GSPC", "CA": "^GSPTSE"}
MIN_NAMES = 10
# known as-traded closes (public record) used to verify the raw-basis reconstruction
RAW_CHECKS = [("AAPL", "2020-08-28", 499.23), ("NVDA", "2024-06-07", 1208.88)]


def market_of(sym: str) -> str | None:
    if sym.startswith("^"):
        return None
    return "CA" if sym.endswith(".TO") else "US"


def build_panels(long: pd.DataFrame, basis: str):
    panels = {}
    for m, idx in MARKETS.items():
        cal = pd.DatetimeIndex(sorted(long.loc[long.symbol == idx, "date"].unique()))
        cal = cal[cal >= pd.Timestamp("2005-01-01")]
        sub = long[long.symbol.map(market_of) == m]
        panels[m] = panel_from_long(sub, basis=basis, calendar=cal)
    return panels


def summarise(ic: pd.DataFrame, h: int) -> dict:
    rows = {"full": ic_summary(ic["ic"], h)}
    for name, a, b in ERAS:
        rows[name] = ic_summary(ic["ic"].loc[a:b], h)
    return rows


def fmt(x, nd=4):
    return "nan" if x is None or not np.isfinite(x) else f"{x:.{nd}f}"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/smoke_test.md")
    args = ap.parse_args(argv)
    t0 = time.time()
    with reader() as conn:
        long = read_long(conn, start="2004-01-01")
    t_read = time.time() - t0
    A = load_alphas()
    lines = []
    out = lines.append

    # ---------------------------------------------------------------- raw-basis verification
    raw_all = panel_from_long(long[long.symbol.map(market_of) == "US"], basis="raw")
    checks = []
    for sym, day, expected in RAW_CHECKS:
        j = list(raw_all.symbols).index(sym)
        i = raw_all.dates.get_loc(pd.Timestamp(day))
        got = raw_all.fields["close"][i, j]
        checks.append((sym, day, expected, got, abs(got / expected - 1) < 0.002))

    results = {}
    timings = {}
    for basis in ("raw", "adjusted"):
        panels = build_panels(long, basis)
        for m, p in panels.items():
            ev = Evaluator(p)
            fwd = {h: forward_returns(p, h) for h in HORIZONS}
            for i in ALPHA_IDS:
                t1 = time.time()
                a = ev.evaluate(A[i].expression)
                timings[(basis, m, i)] = time.time() - t1
                for h in HORIZONS:
                    results[(basis, m, i, h)] = summarise(rank_ic(a, fwd[h], MIN_NAMES), h)
            if basis == "raw":
                results[("shape", m)] = p.shape
    # ---------------------------------------------------------------- all non-industry alphas
    p_us = build_panels(long, "raw")["US"]
    cover = []
    t_all = time.time()
    for i, a in A.items():
        if a.needs_industry or "cap" in a.inputs:
            continue
        t1 = time.time()
        v = Evaluator(p_us).evaluate(a.expression).to_numpy()
        tail = v[a.max_lookback_days + 260:]
        cover.append((i, time.time() - t1, float(np.isfinite(tail).mean())))
    t_all = time.time() - t_all

    # ---------------------------------------------------------------- report
    out("# Smoke test: alphas 1, 6, 12, 101 end to end on the existing `yahoo_ohlcv` symbols")
    out("")
    out(f"Generated by `scripts/smoke_test.py` on {dt.date.today().isoformat()}. Every number below is "
        "computed by that script; rerun it to regenerate this file. Read-only: no DB writes.")
    out("")
    out("**What this is:** a pipeline check (DB -> Panel -> as-traded basis -> parser/evaluator -> "
        "`forward_returns` -> daily rank IC). **What it is not:** evidence about any alpha. The "
        "cross-sections are ~25 US and ~23 TSX symbols including index/sector ETFs, so an IC "
        f"needs only {MIN_NAMES} names per day and its standard error is huge.")
    out("")
    out("## Setup")
    out("")
    for m in MARKETS:
        T, N = results[("shape", m)]
        out(f"- {m} panel: {T} trading days (calendar = {MARKETS[m]} dates since 2005-01-01) x {N} symbols")
    out(f"- DB read: {len(long):,} rows in {t_read:.1f}s")
    out("- Options: default `EvalOptions()` (argmax oldest_1based, adv in shares, min_group_size 5); "
        "vwap proxy (H+L+C)/3; forward returns close-to-close with 1-day implementation lag "
        "(`forward_returns(panel, h)`); NW t-stat with lags = h.")
    out("")
    out("## Raw-basis reconstruction check (as-traded close vs public record)")
    out("")
    out("| symbol | date | expected | reconstructed | ok |")
    out("|---|---|---:|---:|---|")
    for sym, day, exp, got, ok in checks:
        out(f"| {sym} | {day} | {exp:.2f} | {got:.2f} | {'yes' if ok else 'NO'} |")
    out("")
    for h in (5, 1):
        out(f"## Rank IC, horizon {h} day(s), raw basis")
        out("")
        out("| market | alpha | period | mean IC | IC-IR (daily) | NW t | hit rate | days |")
        out("|---|---:|---|---:|---:|---:|---:|---:|")
        for m in MARKETS:
            for i in ALPHA_IDS:
                r = results[("raw", m, i, h)]
                for per in ["full"] + [e[0] for e in ERAS]:
                    s = r[per]
                    out(f"| {m} | {i} | {per} | {fmt(s['mean_ic'])} | {fmt(s['ic_ir'], 3)} | "
                        f"{fmt(s['t_nw'], 2)} | {fmt(s['hit_rate'], 3)} | {s['n_days']} |")
        out("")
    out("## All horizons, full period, raw basis")
    out("")
    out("| market | alpha | " + " | ".join(f"IC h={h} (t)" for h in HORIZONS) + " |")
    out("|---|---:|" + "---:|" * len(HORIZONS))
    for m in MARKETS:
        for i in ALPHA_IDS:
            cells = [f"{fmt(results[('raw', m, i, h)]['full']['mean_ic'])} "
                     f"({fmt(results[('raw', m, i, h)]['full']['t_nw'], 2)})" for h in HORIZONS]
            out(f"| {m} | {i} | " + " | ".join(cells) + " |")
    out("")
    out("## Raw (as-traded) vs split-adjusted basis, horizon 5, full period")
    out("")
    out("Alphas 1 and 6 are price-scale invariant (identical up to split-window masking); 12 and "
        "101 are not (`price_scale_invariant` in alphas.yaml).")
    out("")
    out("| market | alpha | invariant | mean IC raw | mean IC adjusted | difference |")
    out("|---|---:|---|---:|---:|---:|")
    for m in MARKETS:
        for i in ALPHA_IDS:
            a = results[("raw", m, i, 5)]["full"]["mean_ic"]
            b = results[("adjusted", m, i, 5)]["full"]["mean_ic"]
            out(f"| {m} | {i} | {A[i].price_scale_invariant} | {fmt(a)} | {fmt(b)} | {fmt(a - b)} |")
    out("")
    out("## Evaluation time per alpha (seconds, this panel)")
    out("")
    out("| basis | market | " + " | ".join(f"#{i}" for i in ALPHA_IDS) + " |")
    out("|---|---|" + "---:|" * len(ALPHA_IDS))
    for basis in ("raw", "adjusted"):
        for m in MARKETS:
            out(f"| {basis} | {m} | " + " | ".join(f"{timings[(basis, m, i)]:.3f}" for i in ALPHA_IDS) + " |")
    out("")
    out(f"## Coverage: all {len(cover)} non-industry, non-cap alphas on the US panel (raw basis)")
    out("")
    out(f"Total evaluation time {t_all:.1f}s. 'finite' = share of cells that are finite from "
        "one year after each alpha's lookback onward (ETFs and late IPOs lower it).")
    out("")
    low = [c for c in cover if c[2] < 0.5]
    out(f"- alphas with < 50% finite cells: {', '.join(str(c[0]) for c in low) if low else 'none'}")
    out(f"- median finite share: {np.median([c[2] for c in cover]):.3f}; "
        f"slowest: {', '.join(f'#{c[0]} {c[1]:.2f}s' for c in sorted(cover, key=lambda c: -c[1])[:5])}")
    out("")
    out("| alpha | seconds | finite |")
    out("|---:|---:|---:|")
    for i, s, f in cover:
        out(f"| {i} | {s:.3f} | {f:.3f} |")
    Path(args.out).write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out} in {time.time() - t0:.1f}s; raw checks ok={all(c[4] for c in checks)}")


if __name__ == "__main__":
    main()
