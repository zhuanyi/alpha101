#!/usr/bin/env python3
"""Time operators and all 101 alphas on a synthetic panel of the target size (700 x 5,000).

    PYTHONPATH=src python3 scripts/bench_operators.py [--T 5000] [--N 700] [--out docs/performance.md]
"""
from __future__ import annotations

import argparse
import os
import resource
import time
from pathlib import Path

import numpy as np

from alpha101 import Evaluator, load_alphas
from alpha101 import operators as op
from alpha101.synthetic import random_panel


def timed(fn, *a, repeat=2, **k):
    best = float("inf")
    for _ in range(repeat):
        t = time.perf_counter()
        fn(*a, **k)
        best = min(best, time.perf_counter() - t)
    return best


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--T", type=int, default=5000)
    ap.add_argument("--N", type=int, default=700)
    ap.add_argument("--out", default="docs/performance.md")
    a = ap.parse_args(argv)
    p = random_panel(T=a.T, N=a.N, seed=1, n_sectors=11, n_industries=69)
    x, y = p.fields["close"], p.fields["volume"]
    r = op.rank(x)
    cases = [
        ("delta(x, 5)", lambda: op.delta(x, 5)),
        ("rank(x) cross-sectional", lambda: op.rank(x)),
        ("ts_sum(x, 20)", lambda: op.ts_sum(x, 20)),
        ("ts_stddev(x, 20)", lambda: op.ts_stddev(x, 20)),
        ("ts_min(x, 20)", lambda: op.ts_min(x, 20)),
        ("correlation(x, y, 10)", lambda: op.correlation(x, y, 10)),
        ("correlation(x, y, 250)", lambda: op.correlation(x, y, 250)),
        ("covariance(x, y, 10)", lambda: op.covariance(x, y, 10)),
        ("ts_rank(x, 10)", lambda: op.ts_rank(x, 10)),
        ("ts_rank(x, 60)", lambda: op.ts_rank(x, 60)),
        ("ts_argmax(x, 30)", lambda: op.ts_argmax(x, 30)),
        ("decay_linear(x, 20)", lambda: op.decay_linear(x, 20)),
        ("ts_product(x, 15)", lambda: op.ts_product(r, 15)),
        ("indneutralize(x, industry)", lambda: op.indneutralize(x, p.group_chain("industry"))),
        ("scale(x)", lambda: op.scale(x)),
    ]
    rows = [(name, timed(fn)) for name, fn in cases]
    A = load_alphas()
    per_alpha = []
    t_all = time.perf_counter()
    for i, spec in A.items():
        t = time.perf_counter()
        Evaluator(p).evaluate(spec.expression)
        per_alpha.append((i, time.perf_counter() - t))
    t_all = time.perf_counter() - t_all
    peak_mb = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024
    L = []
    L.append(f"# Performance on a synthetic {a.N} x {a.T} panel")
    L.append("")
    L.append(f"Generated by `scripts/bench_operators.py --T {a.T} --N {a.N}` (numpy {np.__version__}, "
             f"{os.cpu_count()} logical CPUs, single process). Best of 2 runs per operator.")
    L.append("")
    L.append("| operator | seconds |")
    L.append("|---|---:|")
    for name, s in sorted(rows, key=lambda r: -r[1]):
        L.append(f"| `{name}` | {s:.3f} |")
    L.append("")
    L.append(f"## All 101 alphas: {t_all:.1f}s total, fresh Evaluator per alpha (no cross-alpha memo); "
             f"peak RSS {peak_mb:.0f} MB")
    L.append("")
    L.append("Slowest 10:")
    L.append("")
    L.append("| alpha | seconds |")
    L.append("|---:|---:|")
    for i, s in sorted(per_alpha, key=lambda r: -r[1])[:10]:
        L.append(f"| {i} | {s:.2f} |")
    L.append("")
    L.append(f"Median alpha: {np.median([s for _, s in per_alpha]):.2f}s.")
    Path(a.out).write_text("\n".join(L) + "\n")
    print("\n".join(L[:30]))


if __name__ == "__main__":
    main()
