#!/usr/bin/env python3
"""Which daily vwap proxy is closer to a bar-built VWAP? (network: Yahoo 1h bars, ~730 days)

    PYTHONPATH=src python3 scripts/vwap_proxy_check.py [--out docs/vwap_proxy_check.md]

"True" vwap is approximated from 60-minute bars: sum(typical_bar * vol_bar) / sum(vol_bar).
Daily OHLC is built from the same bars so both sides share one price basis. Reported per proxy:
median |proxy - vwap| / close (bps), and the mean daily cross-sectional Spearman correlation
between (proxy - close) and (vwap - close), the quantity alphas 11, 25, 42, 47, 57 and 83 use.
Nothing is written to the DB; the result informs the default proxy only.
"""
from __future__ import annotations

import argparse
import datetime as dt
from pathlib import Path

import numpy as np
import pandas as pd

from alpha101.panel import VWAP_PROXIES

SYMBOLS = ["AAPL", "AMZN", "BRK-B", "COST", "GOOGL", "HD", "JNJ", "JPM", "META", "MSFT", "NVDA",
           "PG", "TSLA", "UNH", "V", "XOM", "ATD.TO", "BMO.TO", "BN.TO", "BNS.TO", "CNQ.TO",
           "CNR.TO", "CP.TO", "CSU.TO", "ENB.TO", "MFC.TO", "RY.TO", "SHOP.TO", "SU.TO", "TD.TO",
           "TRP.TO", "WCN.TO"]


def daily_from_bars(sym: str) -> pd.DataFrame:
    import yfinance as yf
    b = yf.download(sym, period="730d", interval="1h", auto_adjust=False, progress=False, threads=False)
    if b is None or b.empty:
        return pd.DataFrame()
    if isinstance(b.columns, pd.MultiIndex):
        b.columns = b.columns.get_level_values(0)
    b = b[b["Volume"] > 0].copy()
    b["day"] = pd.to_datetime(b.index).tz_localize(None).normalize()
    b["tp_v"] = (b["High"] + b["Low"] + b["Close"]) / 3 * b["Volume"]
    g = b.groupby("day")
    d = pd.DataFrame({"open": g["Open"].first(), "high": g["High"].max(), "low": g["Low"].min(),
                      "close": g["Close"].last(), "vwap": g["tp_v"].sum() / g["Volume"].sum(),
                      "bars": g.size()})
    d = d[d["bars"] >= 5]  # drop half days
    d["symbol"] = sym
    return d.reset_index().rename(columns={"day": "date"})


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/vwap_proxy_check.md")
    args = ap.parse_args(argv)
    frames = [daily_from_bars(s) for s in SYMBOLS]
    df = pd.concat([f for f in frames if not f.empty], ignore_index=True)
    got = sorted(df.symbol.unique())
    res = []
    for name, fn in VWAP_PROXIES.items():
        px = fn(df["open"], df["high"], df["low"], df["close"])
        err_bps = (px - df["vwap"]).abs() / df["close"] * 1e4
        tmp = df.assign(p=px - df["close"], v=df["vwap"] - df["close"])
        rhos = []
        for (mkt, _day), g in tmp.groupby([tmp.symbol.str.endswith(".TO"), "date"]):
            if len(g) >= 8:
                rhos.append(g["p"].rank().corr(g["v"].rank()))
        res.append((name, float(err_bps.median()), float(err_bps.quantile(0.9)),
                    float(np.nanmean(rhos)), len(rhos)))
    L = [f"# vwap proxy check ({dt.date.today().isoformat()})", "",
         "Generated by `scripts/vwap_proxy_check.py`. True vwap is approximated from Yahoo 60-minute "
         "bars (typical price x volume per bar), so it is itself an approximation (within-bar "
         "error); daily OHLC is aggregated from the same bars.", "",
         f"Symbols with data: {len(got)} ({', '.join(got)}); day-rows: {len(df):,}; "
         f"range {df.date.min().date()} .. {df.date.max().date()}.", "",
         "| proxy | median abs error (bps of close) | p90 abs error (bps) | mean daily XS Spearman of (proxy-close) vs (vwap-close) | days |",
         "|---|---:|---:|---:|---:|"]
    for name, med, p90, rho, n in res:
        L.append(f"| `{name}` | {med:.1f} | {p90:.1f} | {rho:.3f} | {n} |")
    best = min(res, key=lambda r: r[1])[0]
    L += ["", f"Lowest median error: `{best}`."]
    Path(args.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
